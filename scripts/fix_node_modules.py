#!/usr/bin/env python3
"""
SSR One AI – Monorepo Node Modules Repair Utility
Detects missing .pnpm virtual store, cleans corrupted node_modules, and performs fresh pnpm install.
"""
import sys
import shutil
import subprocess
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
NODE_MODULES = ROOT_DIR / "node_modules"
PNPM_STORE = NODE_MODULES / ".pnpm"


def repair_node_modules():
    print("==================================================")
    print("SSR One AI – Monorepo Node Modules Repair Utility")
    print("==================================================")

    # Check if root node_modules or any sub-app in apps/ is missing node_modules
    apps_missing_modules = [
      app_dir for app_dir in (ROOT_DIR / "apps").iterdir()
      if app_dir.is_dir() and (app_dir / "package.json").exists() and not (app_dir / "node_modules").exists()
    ]

    if NODE_MODULES.exists() and PNPM_STORE.exists() and not apps_missing_modules:
        print("✅ node_modules and .pnpm virtual store are healthy across all apps. Skipping re-install.\n")
        return True

    if apps_missing_modules:
        print(f"⚠️ Found {len(apps_missing_modules)} workspace app(s) missing node_modules ({', '.join(a.name for a in apps_missing_modules)}). Running workspace install...")

    # If node_modules exists but .pnpm is missing, node_modules is corrupted
    if NODE_MODULES.exists() and not PNPM_STORE.exists():
        print("⚠️ Corrupted node_modules detected (missing .pnpm virtual store). Cleaning up...")
        try:
            shutil.rmtree(NODE_MODULES, ignore_errors=True)
            print("Cleaned corrupted node_modules directory.")
        except Exception as e:
            print(f"Warning during cleanup: {e}")

    print("Running fresh monorepo pnpm install...\n")
    try:
        res = subprocess.run("npx pnpm install", shell=True, cwd=str(ROOT_DIR))
        if res.returncode == 0:
            print("\n✅ node_modules dependencies successfully repaired & installed!")
            return True
        else:
            print(f"\n❌ pnpm install exited with code {res.returncode}")
            return False
    except Exception as e:
        print(f"\n❌ Error executing repair: {e}")
        return False


if __name__ == "__main__":
    success = repair_node_modules()
    sys.exit(0 if success else 1)
