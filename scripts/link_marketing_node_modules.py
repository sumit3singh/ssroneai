"""
Utility script to set up node_modules for apps/marketing-web using Windows Junction or symlink from existing workspace node_modules.
"""
import os
import sys
import subprocess
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
ADMIN_NODE_MODULES = ROOT_DIR / "apps" / "platform-admin" / "node_modules"
MARKETING_DIR = ROOT_DIR / "apps" / "marketing-web"
MARKETING_NODE_MODULES = MARKETING_DIR / "node_modules"

def setup_marketing_node_modules():
    print("Setting up node_modules for apps/marketing-web...")
    
    if not ADMIN_NODE_MODULES.exists():
        print(f"Error: {ADMIN_NODE_MODULES} does not exist. Run pnpm install first.")
        sys.exit(1)

    # If marketing-web/node_modules doesn't have .bin, clean and link
    bin_dir = MARKETING_NODE_MODULES / ".bin"
    if not bin_dir.exists():
        print(f"Linking node_modules from {ADMIN_NODE_MODULES} to {MARKETING_NODE_MODULES}...")
        
        if MARKETING_NODE_MODULES.exists():
            import shutil
            shutil.rmtree(MARKETING_NODE_MODULES, ignore_errors=True)
            
        # Create directory junction on Windows
        cmd = f'cmd /c mklink /J "{MARKETING_NODE_MODULES}" "{ADMIN_NODE_MODULES}"'
        res = subprocess.run(cmd, shell=True, capture_output=True, text=True)
        if res.returncode == 0:
            print("✅ Successfully linked node_modules junction for apps/marketing-web!")
        else:
            print(f"Junction attempt fallback: {res.stderr}")
            import shutil
            shutil.copytree(ADMIN_NODE_MODULES, MARKETING_NODE_MODULES, dirs_exist_ok=True)
            print("✅ Successfully copied node_modules for apps/marketing-web!")

if __name__ == "__main__":
    setup_marketing_node_modules()
